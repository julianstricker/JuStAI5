"""Display port.

Content is never raw HTML generated by an LLM. It is a *presentation document*:
a tree of typed components (see the core render schema) that each display client
renders with its own trusted component implementations.
"""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable

from pydantic import BaseModel


class DisplayAck(BaseModel):
    presentation_id: str
    status: str  # displayed | failed | closed
    error: str | None = None


@runtime_checkable
class DisplaySink(Protocol):
    async def show(self, presentation_id: str, document: dict[str, Any]) -> None:
        """Send a presentation. Acknowledgements arrive asynchronously via events."""
        ...

    async def close(self, presentation_id: str) -> None: ...
